#!/usr/bin/env node
//=============================================================================
// gen-constants.js - write src/constants/generated.txt from the C# server's
// NavConstants.cs and BotConstants.cs.
//
//   node tools/gen-constants.js [--server <C# server checkout>]
//
// Each `public const T Name = value;   // GML_NAME` becomes `GML_NAME value`.
// A constant with no GML name in its comment gets NAV_/BOT_ plus its C# name in
// SCREAMING_SNAKE. The C# name is kept as a trailing comment so a porter can
// find a constant from the C# side.
//=============================================================================
'use strict';
const fs = require('fs');
const path = require('path');
const args = process.argv.slice(2);
const si = args.indexOf('--server');
const SERVER = si >= 0 ? args[si + 1] : 'D:/Code/gg2-server';
const OUT = path.resolve(__dirname, '..', 'src', 'constants', 'generated.txt');

function snake(name) {
  return name.replace(/([a-z0-9])([A-Z])/g, '$1_$2').replace(/([A-Z])([A-Z][a-z])/g, '$1_$2').toUpperCase();
}

const lines = ['// Generated by tools/gen-constants.js from the C# server. Do not edit; regenerate.'];
const seen = new Map();
for (const [file, prefix] of [['src/GG2.Protocol/NavConstants.cs', 'NAV_'], ['src/GG2.Protocol/BotConstants.cs', 'BOT_']]) {
  const src = fs.readFileSync(path.join(SERVER, file), 'utf8');
  lines.push('', `// ${file}`);
  const re = /public const (?:int|double|float|byte|short|long|bool) (\w+) = ([^;]+);[ \t]*(?:\/\/\s*([A-Z][A-Z0-9_]+))?/g;
  let m;
  while ((m = re.exec(src))) {
    const [, cs, rawValue, gml] = m;
    let value = rawValue.trim().replace(/_/g, '').replace(/[dDfFmM]$/, '');
    if (value === 'true') value = '1';
    if (value === 'false') value = '0';
    if (!/^-?[0-9]+(\.[0-9]+)?(e-?[0-9]+)?$/i.test(value)) {
      lines.push(`// skipped ${cs} = ${rawValue.trim()} (not a literal)`);
      continue;
    }
    const name = gml || prefix + snake(cs);
    if (seen.has(name)) {
      lines.push(`// skipped ${cs}: ${name} already defined`);
      continue;
    }
    seen.set(name, value);
    lines.push(`${name} ${value} // ${path.basename(file, '.cs')}.${cs}`);
  }
}
fs.mkdirSync(path.dirname(OUT), { recursive: true });
fs.writeFileSync(OUT, lines.join('\n') + '\n');
console.log(`gen-constants: ${seen.size} constants -> ${path.relative(process.cwd(), OUT)}`);
